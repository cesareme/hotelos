const requestCounters = new Map<string, number>();

/** Test hook: forget the per-channel request counters used by `failEvery`. */
export function resetSimulatorCounters(): void {
  requestCounters.clear();
}

function rateLimitedBody(provider: SimulatorProvider): { body: string; contentType: string } {
  if (provider === "channex") {
    return { body: JSON.stringify({ errors: { code: "too_many_requests", title: "Rate limit exceeded (simulated)" } }), contentType: "application/json" };
  }
  if (provider === "expedia") {
    return { body: eqcRs("AvailRateUpdateRS", { code: "4000", message: "Too many requests (simulated)" }), contentType: "text/xml" };
  }
  return { body: otaRs("OTA_ErrorRS", [{ code: "429", shortText: "Too many requests (simulated)" }], []), contentType: "text/xml" };
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Runs one simulated request. Applies the failure-injection knobs first (429
 * every N-th request, latency / timeout), then validates against the provider
 * schema. Never throws: a malformed body is a provider error response.
 */
export async function runSimulator(req: SimulatorRequest): Promise<SimulatorResponse> {
  const counterKey = `${req.channelId ?? "anon"}:${req.provider}`;
  const count = (requestCounters.get(counterKey) ?? 0) + 1;
  requestCounters.set(counterKey, count);
  const failEvery = req.options?.failEvery ?? 0;
  const latencyMs = req.options?.latencyMs ?? 0;
  const timeoutMs = req.timeoutMs ?? 30_000;
  const contentType = req.provider === "channex" ? "application/json" : "text/xml";

  if (latencyMs > 0 && latencyMs >= timeoutMs) {
    return { status: 0, body: "", contentType, timedOut: true, accepted: 0, rejected: [], errors: [`Simulated timeout after ${timeoutMs} ms`], warnings: [] };
  }
  if (latencyMs > 0) await sleep(Math.min(latencyMs, 5_000));

  if (failEvery > 0 && count % failEvery === 0) {
    const limited = rateLimitedBody(req.provider);
    return { status: 429, body: limited.body, contentType: limited.contentType, timedOut: false, accepted: 0, rejected: [], errors: ["Rate limited (simulated 429)"], warnings: [] };
  }

  const result =
    req.provider === "booking"
      ? simulateBookingOta(req.body)
      : req.provider === "channex"
        ? simulateChannex(req.endpoint, req.body)
        : simulateExpediaEqc(req.body);
  return { ...result, contentType, timedOut: false };
}
